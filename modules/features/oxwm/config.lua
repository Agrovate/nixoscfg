-- ============================================================================
-- OXWM
-- ============================================================================

oxwm.set_terminal("ghostty")
oxwm.set_modkey("Mod1")

oxwm.set_tags({
    "1",
    "2",
    "3",
    "4",
    "5",
    "6",
    "7",
    "8",
    "9",
})

-- ============================================================================
-- Gaps
-- ============================================================================

oxwm.gaps.set_enabled(true)
oxwm.gaps.set_inner(5, 5)
oxwm.gaps.set_outer(5, 5)

-- ============================================================================
-- Borders
-- ============================================================================

oxwm.border.set_width(2)
oxwm.border.set_focused_color("#4c566a")
oxwm.border.set_unfocused_color("#2e3440")

-- ============================================================================
-- Terminal
-- ============================================================================

oxwm.key.bind({ "Mod4" }, "Return", oxwm.spawn("ghostty"))

-- ============================================================================
-- Window management
-- ============================================================================

oxwm.key.bind({ "Mod4" }, "Q", oxwm.client.kill())

-- ============================================================================
-- Workspaces / Tags
-- ============================================================================

oxwm.key.bind({ "Mod4" }, "1", oxwm.tag.view(1))

oxwm.key.bind({ "Mod4" }, "2", oxwm.tag.view(2))

oxwm.key.bind({ "Mod4" }, "3", oxwm.tag.view(3))

oxwm.key.bind({ "Mod4" }, "4", oxwm.tag.view(4))

-- ============================================================================
-- Move windows to tags
-- ============================================================================

oxwm.key.bind({ "Mod4", "Shift" }, "1", oxwm.tag.move_to(1))

oxwm.key.bind({ "Mod4", "Shift" }, "2", oxwm.tag.move_to(2))

oxwm.key.bind({ "Mod4", "Shift" }, "3", oxwm.tag.move_to(3))

oxwm.key.bind({ "Mod4", "Shift" }, "4", oxwm.tag.move_to(4))

-- ============================================================================
-- Launcher
-- ============================================================================

oxwm.key.bind({ "Mod4" }, "D", oxwm.spawn("dmenu_run"))

-- ============================================================================
-- Screenshot
-- ============================================================================

oxwm.key.bind({ "Mod4", "Shift" }, "F3", oxwm.spawn("sh -c 'maim -s | xclip -selection clipboard -t image/png'"))

-- ============================================================================
-- Reload / quit
-- ============================================================================

-- OXWM's default reload binding is Mod+Shift+R.
-- OXWM's default quit binding is Mod+Shift+Q.

-- ============================================================================
-- Autostart
-- ============================================================================

oxwm.spawn("xrandr --auto")
